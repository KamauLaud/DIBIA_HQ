// board.mjs — the DIBIA chip on a motherboard: traces from the die to the subsystems the guild is building.
// Data: data/ventures.json. Output: static HTML (no JS needed) + assets/board.css.
// Desktop: chip centred, traces drawn in SVG to subsystem modules. Narrow screens: chip on top, modules stacked, traces hidden.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(new URL('..', import.meta.url).pathname);
const V = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/ventures.json'), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Board geometry (viewBox units). Chip die sits in the middle; modules on three sides.
const W = 1200, H = 680;
const CHIP = { x: 410, y: 150, w: 380, h: 270 };
const SLOTS = {
  left:   { x: 20,  y: 60,  w: 310, h: 230, pin: [CHIP.x, 250], route: (m) => [[CHIP.x, 250], [370, 250], [370, 175], [m.x + m.w, 175]] },
  right:  { x: 870, y: 60,  w: 310, h: 230, pin: [CHIP.x + CHIP.w, 250], route: (m) => [[CHIP.x + CHIP.w, 250], [830, 250], [830, 175], [m.x, 175]] },
  bottom: { x: 160, y: 490, w: 340, h: 170, pin: [520, CHIP.y + CHIP.h], route: (m) => [[520, CHIP.y + CHIP.h], [520, 455], [330, 455], [330, m.y]] },
  socket: { x: 700, y: 490, w: 340, h: 170, pin: [680, CHIP.y + CHIP.h], route: (m) => [[680, CHIP.y + CHIP.h], [680, 455], [870, 455], [870, m.y]] }
};

export function renderBoard({ id = 'ventures', heading = true } = {}) {
  const pct = (v, of) => `${(v / of * 100).toFixed(3)}%`;
  const place = (s) => `left:${pct(s.x, W)};top:${pct(s.y, H)};width:${pct(s.w, W)};height:${pct(s.h, H)}`;
  const traces = [];
  const mods = [];
  for (const v of V.subsystems) {
    const s = SLOTS[v.slot];
    const pts = s.route(s);
    const d = pts.map((p, i) => `${i ? 'L' : 'M'}${p[0]} ${p[1]}`).join(' ');
    traces.push(`<path class="bd-tr" d="${d}"/><path class="bd-tr bd-pulse" d="${d}"/>`);
    const link = v.link ? `<a class="bd-more" href="${v.link}">${esc(v.linkLabel || 'More')} →</a>` : '';
    mods.push(`<article class="bd-mod" data-slot="${v.slot}" style="${place(s)}"><div class="bd-st"><span class="bd-led" data-s="${v.statusKey}"></span>${esc(v.status)}</div><div class="bd-busl">${esc(v.bus)}</div><h3>${esc(v.name)}</h3><p>${esc(v.blurb)}</p>${link}</article>`);
  }
  // open socket: ventures not started yet
  const sk = SLOTS.socket, spts = sk.route(sk);
  traces.push(`<path class="bd-tr bd-tr-open" d="${spts.map((p, i) => `${i ? 'L' : 'M'}${p[0]} ${p[1]}`).join(' ')}"/>`);
  mods.push(`<article class="bd-mod bd-socket" data-slot="socket" style="${place(sk)}"><div class="bd-st"><span class="bd-led" data-s="open"></span>OPEN SOCKETS · NOT STARTED</div><div class="bd-busl">EXPANSION SLOTS</div><ul>${V.later.map((l) => `<li><b>${esc(l.name)}</b> ${esc(l.blurb)}</li>`).join('')}</ul></article>`);
  // pins on the die edges
  const pins = [];
  for (let i = 0; i < 15; i++) {
    const x = CHIP.x + 18 + i * ((CHIP.w - 36) / 14);
    pins.push(`<rect class="bd-pin" x="${x - 3}" y="${CHIP.y - 12}" width="6" height="12"/><rect class="bd-pin" x="${x - 3}" y="${CHIP.y + CHIP.h}" width="6" height="12"/>`);
  }
  for (let i = 0; i < 10; i++) {
    const y = CHIP.y + 18 + i * ((CHIP.h - 36) / 9);
    pins.push(`<rect class="bd-pin" x="${CHIP.x - 12}" y="${y - 3}" width="12" height="6"/><rect class="bd-pin" x="${CHIP.x + CHIP.w}" y="${y - 3}" width="12" height="6"/>`);
  }

  const head = heading ? `<div class="bd-head"><div class="bd-eyebrow">${esc(V.eyebrow)}</div><h2>${esc(V.title)}</h2><p>${esc(V.lede)}</p></div>` : '';
  const html = `
<section class="bd" id="${id}" aria-labelledby="${id}-h">
  <div class="bd-wrap">${head.replace('<h2>', `<h2 id="${id}-h">`)}
    <div class="bd-board" role="group" aria-label="${esc(V.ariaLabel)}">
      <svg class="bd-svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="none" aria-hidden="true">${traces.join('')}${pins.join('')}</svg>
      <div class="bd-chip" style="${place(CHIP)}"><img src="assets/brand/dibia-chip.webp" alt="DIBIA Netrunners chip logo" width="960" height="680"></div>
      ${mods.join('\n      ')}
    </div>
  </div>
</section>`;
  fs.writeFileSync(path.join(ROOT, 'assets/board.css'), CSS);
  return html;
}

