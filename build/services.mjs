// services.mjs — the Marketplace service list, built from dossier/members.js.
// A service is listed only if at least one Dossier member offers it, with every member who offers it.
// Static HTML (the list is complete with JS off); site.js adds the search filter.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const ROOT = path.resolve(new URL('..', import.meta.url).pathname);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function loadDossier() {
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'dossier/members.js'), 'utf8'), ctx);
  return ctx.window.DIBIA_DOSSIER;
}

export function renderServices() {
  const D = loadDossier();
  const rows = D.services.map((s) => ({ ...s, by: D.members.filter((m) => (m.jobs || []).includes(s.id)) })).filter((s) => s.by.length);
  const cards = rows.map((s, i) => {
    const who = s.by.map((m) => `<a href="dossier.html#op-${m.id}">${esc(m.name)}</a>`).join(' · ');
    const search = [s.title, s.short, ...s.by.map((m) => `${m.name} ${m.cell} ${(m.skills || []).join(' ')}`)].join(' ').toLowerCase();
    return `<li class="sv" data-search="${esc(search)}"><span class="sv-n">${String(i + 1).padStart(2, '0')}</span><div><h3>${esc(s.title)}</h3><div class="sv-t">${esc(s.short)}</div><div class="sv-by">Offered by ${who}</div></div></li>`;
  }).join('');
  fs.writeFileSync(path.join(ROOT, 'assets/services.css'), CSS);
  return `
<div class="svs">
  <div class="sv-bar"><input type="search" class="sv-q" placeholder="Search services, skills, or people" aria-label="Search services" data-svc-search><span class="sv-count" aria-live="polite">${rows.length} SERVICES · ${D.members.length} MEMBERS</span></div>
  <ol class="sv-list">${cards}</ol>
  <p class="sv-empty" hidden>No service matches that search. Send a brief anyway and we will find the right person.</p>
</div>`;
}

