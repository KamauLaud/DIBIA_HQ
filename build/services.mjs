// Founders (org.html): every Dossier member with founder: true, in Dossier order.
export function renderFounders() {
  const D = loadDossier();
  const cards = D.members.filter((m) => m.founder).map((m) => {
    const links = Object.entries(m.links || {}).map(([k, u]) => `<a href="${esc(u)}">${esc(k)}</a>`).join('');
    return `<article class="fd"><img src="${esc(m.photo)}" alt="${esc(m.name)}" loading="lazy"><div class="fd-b"><div class="fd-r">CO-FOUNDER · ${esc((m.cell || '').toUpperCase())}</div><h3>${esc(m.name)}</h3><p>${esc(m.headline)}</p><ul>${(m.proof || []).map((x) => `<li>${esc(x)}</li>`).join('')}</ul><div class="fd-l"><a href="dossier.html#op-${m.id}">Dossier profile</a>${links}</div></div></article>`;
  }).join('');
  fs.writeFileSync(path.join(ROOT, 'assets/founders.css'), FOUNDERS_CSS);
  return `
<section class="fds" id="founders" aria-labelledby="fd-h"><div class="fds-w">
  <div class="fds-e">THE FOUNDERS</div>
  <h2 id="fd-h">Who started DIBIA.</h2>
  <div class="fd-g">${cards}</div>
</div></section>`;
}

